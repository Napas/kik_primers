// Builds site/lib/basemap.js from Natural Earth (public domain) via world-atlas TopoJSON.
// Run once: deno run -A tools/make-basemap.ts
const URL_ = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json";
const OUT = new URL("../site/lib/basemap.js", import.meta.url);
const BOX = { lonMin: -10, lonMax: 45, latMin: 35, latMax: 71 };
const SCALE = 10; // pixels per degree
const W = (BOX.lonMax - BOX.lonMin) * SCALE;
const H = (BOX.latMax - BOX.latMin) * SCALE;

type Pt = [number, number];
const res = await fetch(URL_);
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const topo = await res.json();
const { scale, translate } = topo.transform;

// Decode delta-encoded quantized arcs to lon/lat.
const arcs: Pt[][] = topo.arcs.map((arc: Pt[]) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]] as Pt;
  });
});

function ring(indices: number[]): Pt[] {
  const pts: Pt[] = [];
  for (const i of indices) {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
}

// Sutherland-Hodgman clip of a ring to the box.
function clip(pts: Pt[]): Pt[] {
  const edges: [(p: Pt) => boolean, (a: Pt, b: Pt) => Pt][] = [
    [(p) => p[0] >= BOX.lonMin, (a, b) => at(a, b, 0, BOX.lonMin)],
    [(p) => p[0] <= BOX.lonMax, (a, b) => at(a, b, 0, BOX.lonMax)],
    [(p) => p[1] >= BOX.latMin, (a, b) => at(a, b, 1, BOX.latMin)],
    [(p) => p[1] <= BOX.latMax, (a, b) => at(a, b, 1, BOX.latMax)],
  ];
  for (const [inside, cut] of edges) {
    const out: Pt[] = [];
    pts.forEach((cur, i) => {
      const prev = pts[(i + pts.length - 1) % pts.length];
      if (inside(cur)) {
        if (!inside(prev)) out.push(cut(prev, cur));
        out.push(cur);
      } else if (inside(prev)) out.push(cut(prev, cur));
    });
    pts = out;
    if (!pts.length) break;
  }
  return pts;
}
function at(a: Pt, b: Pt, axis: 0 | 1, v: number): Pt {
  const t = (v - a[axis]) / (b[axis] - a[axis]);
  return axis === 0 ? [v, a[1] + t * (b[1] - a[1])] : [a[0] + t * (b[0] - a[0]), v];
}

const r1 = (n: number) => Math.round(n * 10) / 10;
const MIN_SIZE = 1.5; // px: smaller rings are dropped
const TOLERANCE = 0.5; // px: Douglas-Peucker

function simplify(pts: Pt[]): Pt[] {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
  let max = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const p = pts[i];
    const dist = len === 1 && a[0] === b[0] && a[1] === b[1]
      ? Math.hypot(p[0] - a[0], p[1] - a[1])
      : Math.abs((b[0] - a[0]) * (a[1] - p[1]) - (a[0] - p[0]) * (b[1] - a[1])) / len;
    if (dist > max) [max, idx] = [dist, i];
  }
  if (max <= TOLERANCE) return [a, b];
  return [...simplify(pts.slice(0, idx + 1)).slice(0, -1), ...simplify(pts.slice(idx))];
}

let d = "";
for (const g of topo.objects.countries.geometries) {
  const polys: number[][][] = g.type === "Polygon" ? [g.arcs] : g.type === "MultiPolygon" ? g.arcs : [];
  for (const poly of polys) {
    for (const r of poly) {
      const clipped = clip(ring(r));
      if (clipped.length < 3) continue;
      const px: Pt[] = clipped.map(([lon, lat]) => [(lon - BOX.lonMin) * SCALE, (BOX.latMax - lat) * SCALE]);
      const xs = px.map((p) => p[0]), ys = px.map((p) => p[1]);
      if (Math.max(...xs) - Math.min(...xs) < MIN_SIZE && Math.max(...ys) - Math.min(...ys) < MIN_SIZE) continue;
      // Split the closed ring at its farthest point so simplification keeps both halves.
      let far = 0, fd = 0;
      px.forEach((p, i) => { const q = Math.hypot(p[0] - px[0][0], p[1] - px[0][1]); if (q > fd) [fd, far] = [q, i]; });
      const s = [...simplify(px.slice(0, far + 1)).slice(0, -1), ...simplify([...px.slice(far), px[0]]).slice(0, -1)];
      // Round, drop consecutive duplicates, emit relative deltas.
      let cx = NaN, cy = NaN, start = "";
      const deltas: number[] = [];
      for (const [x0, y0] of s) {
        const x = r1(x0), y = r1(y0);
        if (!start) start = `M${x} ${y}`;
        else if (x !== cx || y !== cy) deltas.push(r1(x - cx), r1(y - cy));
        cx = x;
        cy = y;
      }
      if (deltas.length >= 4) d += `${start}l${deltas.join(" ").replace(/ -/g, "-")}z`;
    }
  }
}

const js = `// Generated by tools/make-basemap.ts from Natural Earth (public domain). Do not edit.
export const BASEMAP = {
  box: ${JSON.stringify(BOX)},
  width: ${W},
  height: ${H},
  path: ${JSON.stringify(d)},
};

/** Equirectangular position of (lat, lon) in basemap pixels. */
export function project(lat, lon) {
  const { lonMin, lonMax, latMin, latMax } = BASEMAP.box;
  return {
    x: ((lon - lonMin) / (lonMax - lonMin)) * BASEMAP.width,
    y: ((latMax - lat) / (latMax - latMin)) * BASEMAP.height,
    inside: lon >= lonMin && lon <= lonMax && lat >= latMin && lat <= latMax,
  };
}
`;
await Deno.writeTextFile(OUT, js);
console.log("wrote", OUT.pathname, js.length, "bytes");
